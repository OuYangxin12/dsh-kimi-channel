#!/usr/bin/env node
/**
 * End-to-end verification for the Kimi channel.
 *
 * Boots a throwaway DSH profile (its own DSH_HOME, its own loopback ports),
 * installs the workspace plugin by link, then drives it through the Kimi-side
 * client exactly as Kimi Code would:
 *
 *   1. health                - channel up, token accepted
 *   2. tools turn            - read two files, write one, receive the trajectory
 *   3. session reuse         - a second turn on the same conversation key
 *   4. approval allow        - bash escalated with danger-full-access, granted
 *   5. approval deny         - the same escalation refused, turn still completes
 *   6. replay                - events.resume after a reconnect
 *   7. protocol hardening    - bad version/method answered without dropping the socket
 *
 * Usage:
 *   node e2e/run-e2e.mjs [--keep] [--no-model]
 *
 *   --keep      keep the temporary DSH home and workspace for inspection
 *   --no-model  only run protocol/transport checks (no model API needed)
 *
 * Needs a model route in the patch: OPENCODE_API_KEY or OPENCODE_GO_API_KEY
 * from the environment, or read from ~/.config/secrets.env.
 */
import { spawn, spawnSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'

const WORKSPACE = path.resolve(import.meta.dirname, '..')
const PLUGIN_DIR = path.join(WORKSPACE, 'kimi-channel')
const CLIENT = path.join(WORKSPACE, 'kimi-skill', 'dsh-channel', 'client.mjs')
const ROOT = path.join(WORKSPACE, '.e2e-run')
const DSH_HOME = path.join(ROOT, 'dsh-home')
const WORK = path.join(ROOT, 'work')
const PROFILE = 'e2e'
const keep = process.argv.includes('--keep')
const noModel = process.argv.includes('--no-model')

const checks = []
const log = (message) => process.stderr.write(`[e2e] ${message}\n`)

/** Record one assertion and print its outcome immediately. */
function check(name, ok, detail) {
  checks.push({ name, ok: Boolean(ok), detail })
  log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok || detail === undefined ? '' : `: ${detail}`}`)
  return ok
}

/** Ask the OS for a free loopback port. */
function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer()
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      const { port } = server.address()
      server.close(() => resolve(port))
    })
  })
}

/** Read one KEY=value from the secrets file, tolerating `export` and quotes. */
function secretValue(name) {
  if (process.env[name]) return process.env[name]
  try {
    const text = fs.readFileSync(path.join(os.homedir(), '.config', 'secrets.env'), 'utf8')
    const match = new RegExp(`^\\s*(?:export\\s+)?${name}=["']?([^"'\\n]+)["']?\\s*$`, 'm').exec(text)
    return match?.[1]
  } catch {
    return undefined
  }
}

/** Spawn the DSH web app in the throwaway home and wait for the channel. */
async function bootDsh(channelPort) {
  const apiKey = secretValue('OPENCODE_GO_API_KEY') ?? secretValue('OPENCODE_API_KEY')
  if (!apiKey && !noModel) throw new Error('no OPENCODE_GO_API_KEY / OPENCODE_API_KEY for the model route (pass --no-model to skip model scenarios)')

  spawnSync('dsh', ['--profile', PROFILE, '--from-default-profile', 'web', '--dump-config'], {
    env: { ...process.env, DSH_HOME },
    encoding: 'utf8',
  })
  const profileDir = path.join(DSH_HOME, 'profiles', PROFILE)
  if (!fs.existsSync(path.join(profileDir, 'cordis.patch.yml'))) throw new Error('failed to create the throwaway profile')

  fs.mkdirSync(path.join(profileDir, 'node_modules'), { recursive: true })
  fs.symlinkSync(PLUGIN_DIR, path.join(profileDir, 'node_modules', 'dsh-kimi-channel'))

  const patch = `# generated by e2e/run-e2e.mjs
- id: llm-pi-ai
  name: '@deepseek-ai/dsh-llm-pi-ai'
  config:
    providers:
      opencode-go:
        apiKeyEnv: OPENCODE_GO_API_KEY
        models:
          - id: deepseek-v4.1-flash
            contextWindow: 1000000
            maxTokens: 128000
- id: agent-default-model
  name: '@deepseek-ai/dsh-agent-default-model'
  config:
    provider: opencode-go
    model: deepseek-v4.1-flash
    reasoningEffort: high
- insert:
    - id: kimi-channel
      name: 'dsh-kimi-channel'
      config:
        port: ${channelPort}
`
  fs.writeFileSync(path.join(profileDir, 'cordis.patch.yml'), patch)
  fs.writeFileSync(
    path.join(DSH_HOME, 'kimi-channel.json'),
    `${JSON.stringify(
      {
        port: channelPort,
        tokenFile: path.join(DSH_HOME, 'kimi-channel.token'),
        sessionMapFile: path.join(DSH_HOME, 'kimi-channel-sessions.json'),
        autoAllowTools: ['read', 'glob', 'grep'],
        allowCwdRoots: [WORK],
        defaultCwd: WORK,
        agent: { provider: 'opencode-go', model: 'deepseek-v4.1-flash', reasoningEffort: 'high' },
        interactionTimeoutMs: 60000,
      },
      null,
      2,
    )}\n`,
  )

  const child = spawn('dsh', ['--profile', PROFILE, '--host', '127.0.0.1', '--port', '0', '--no-open'], {
    env: { ...process.env, DSH_HOME, OPENCODE_GO_API_KEY: apiKey, OPENCODE_API_KEY: apiKey },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  let output = ''
  child.stdout.on('data', (chunk) => {
    output += chunk
  })
  child.stderr.on('data', (chunk) => {
    output += chunk
  })

  const tokenFile = path.join(DSH_HOME, 'kimi-channel.token')
  const deadline = Date.now() + 90_000
  while (Date.now() < deadline) {
    if (fs.existsSync(tokenFile)) {
      const token = fs.readFileSync(tokenFile, 'utf8').trim()
      if (token.length >= 32) {
        const healthy = await fetch(`http://127.0.0.1:${channelPort}/healthz`).then((response) => response.ok).catch(() => false)
        if (healthy) return { child, token, output: () => output }
      }
    }
    if (child.exitCode !== null) throw new Error(`DSH exited during boot (code ${child.exitCode}):\n${output.slice(-4000)}`)
    await new Promise((resolve) => setTimeout(resolve, 500))
  }
  throw new Error(`channel did not become healthy:\n${output.slice(-4000)}`)
}

/** Run the Kimi client and parse its JSON-lines output. */
function runClient(args, timeoutMs = 300_000) {
  const result = spawnSync(process.execPath, [CLIENT, ...args, '--dsh-home', DSH_HOME, '--json', '--quiet'], {
    encoding: 'utf8',
    timeout: timeoutMs,
    maxBuffer: 64 * 1024 * 1024,
  })
  const frames = []
  for (const line of String(result.stdout ?? '').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed.startsWith('{')) continue
    try {
      frames.push(JSON.parse(trimmed))
    } catch {
      /* not a frame */
    }
  }
  return { code: result.status, frames, stderr: String(result.stderr ?? ''), stdout: String(result.stdout ?? '') }
}

/** All channel frames of one type. */
const eventsOf = (frames, name) => frames.filter((frame) => frame.t === 'evt' && frame.event === name)

async function main() {
  log(`workspace: ${WORKSPACE}`)
  fs.rmSync(ROOT, { recursive: true, force: true })
  fs.mkdirSync(WORK, { recursive: true })
  fs.mkdirSync(DSH_HOME, { recursive: true })
  fs.writeFileSync(path.join(WORK, 'a.txt'), 'alpha line\n')
  fs.writeFileSync(path.join(WORK, 'b.txt'), 'beta line\n')

  const channelPort = await freePort()
  log(`booting DSH in ${DSH_HOME} (channel port ${channelPort})`)
  let booted
  try {
    booted = await bootDsh(channelPort)

    check('token file exists', fs.existsSync(path.join(DSH_HOME, 'kimi-channel.token')))
    const tokenMode = fs.statSync(path.join(DSH_HOME, 'kimi-channel.token')).mode & 0o777
    check('token file is 0600', tokenMode === 0o600, `mode ${tokenMode.toString(8)}`)

    const health = runClient(['health'])
    check('health exits 0', health.code === 0, health.stderr.trim())
    check('health reports ok', health.frames.some((frame) => frame.ok === true) || health.stdout.includes('"ok": true'))

    if (!noModel) {
      // 1. A real turn with file tools.
      const first = runClient([
        'run',
        '--task',
        'Read a.txt and b.txt in the current directory, then overwrite a.txt with the exact contents of b.txt followed by the contents of a.txt. Use the file tools.',
        '--cwd',
        WORK,
        '--conversation',
        'e2e-tools',
        '--allow',
        'write,edit,bash',
      ])
      check('tools turn exits 0', first.code === 0, first.stderr.trim().slice(-800))
      const firstFinal = eventsOf(first.frames, 'final').at(-1)
      const firstSession = eventsOf(first.frames, 'session').at(-1)
      check('tools turn produced a final payload', Boolean(firstFinal))
      check('tools turn used tools', Boolean(firstFinal?.data.trajectory?.some((entry) => entry.type === 'tool_call')))
      check(
        'a.txt contains b.txt then a.txt contents',
        fs.readFileSync(path.join(WORK, 'a.txt'), 'utf8') === 'beta line\nalpha line\n',
        JSON.stringify(fs.readFileSync(path.join(WORK, 'a.txt'), 'utf8')),
      )
      check('tools turn reported usage', Boolean(firstFinal?.data.usage))
      check('session id is channel-minted', String(firstSession?.data?.sessionId ?? '').startsWith('kimi-'))

      // 2. Session reuse on the same conversation key.
      const second = runClient([
        'run',
        '--task',
        'Reply with just the single word RESUME_OK and nothing else.',
        '--cwd',
        WORK,
        '--conversation',
        'e2e-tools',
        '--timeout',
        '120000',
      ])
      const secondSession = eventsOf(second.frames, 'session').at(-1)
      const secondTurn = eventsOf(second.frames, 'turn_start').at(-1)
      check('second turn exits 0', second.code === 0, second.stderr.trim().slice(-800))
      check('second turn reuses the session', secondSession?.data?.sessionId === firstSession?.data?.sessionId, `${firstSession?.data?.sessionId} vs ${secondSession?.data?.sessionId}`)
      check('second turn is turn 2 or later', (secondTurn?.data?.turn ?? 0) >= 2, `turn ${secondTurn?.data?.turn}`)

      // 3. Approval granted.
      const approved = runClient([
        'run',
        '--task',
        'Use the bash tool to run: echo approval-probe. Pass sandbox_permissions=danger-full-access so an approval prompt appears. Do not explain.',
        '--cwd',
        WORK,
        '--conversation',
        'e2e-approval-allow',
        '--allow',
        'bash',
        '--timeout',
        '120000',
      ])
      const approveInteraction = eventsOf(approved.frames, 'interaction').at(-1)
      const approveResult = eventsOf(approved.frames, 'tool_result').at(-1)
      check('approval turn exits 0', approved.code === 0, approved.stderr.trim().slice(-800))
      check('approval prompt was forwarded', approveInteraction?.data?.kind === 'approval' && approveInteraction?.data?.toolName === 'bash')
      check('approval prompt carried a reason', typeof approveInteraction?.data?.reason === 'string' && approveInteraction.data.reason.length > 0)
      check('approved bash ran', approveResult?.data?.ok === true && String(approveResult.data.text).includes('approval-probe'), String(approveResult?.data?.text).slice(0, 200))

      // 4. Manager loop: submit returns at once, watch follows to final, report reads it back.
      const managerKey = 'e2e-manager'
      const submitted = runClient([
        'submit',
        '--task',
        'Read a.txt and reply with its exact first line only, no extra words.',
        '--cwd',
        WORK,
        '--conversation',
        managerKey,
      ])
      const submitLine = submitted.stdout
        .split('\n')
        .map((line) => line.trim())
        .find((line) => line.startsWith('{') && line.includes('"command":"submitted"'))
      const submitResult = submitLine ? JSON.parse(submitLine) : undefined
      check('submit returns a session and message id', submitted.code === 0 && Boolean(submitResult?.sessionId && submitResult?.messageId), submitted.stderr.trim().slice(-500))

      const watched = runClient(['watch', '--conversation', managerKey, '--since', '0', '--timeout', '180000'], 240_000)
      const watchedFinal = eventsOf(watched.frames, 'final').at(-1)
      check('watch follows the submitted turn to final', watched.code === 0 && Boolean(watchedFinal), watched.stderr.trim().slice(-800))
      check('watch final contains the worker answer', String(watchedFinal?.data?.text ?? '').trim().includes('beta line'), String(watchedFinal?.data?.text ?? '').slice(0, 200))

      const reported = spawnSync(process.execPath, [CLIENT, 'report', '--conversation', managerKey, '--dsh-home', DSH_HOME, '--json', '--quiet'], {
        encoding: 'utf8',
        timeout: 60_000,
      })
      let reportSnapshot
      try {
        reportSnapshot = JSON.parse(String(reported.stdout ?? ''))
      } catch {
        reportSnapshot = undefined
      }
      check('report returns the same final payload', reported.status === 0 && reportSnapshot?.lastFinal?.text?.trim().includes('beta line'), String(reported.stdout ?? reported.stderr).slice(0, 300))

      // 5. Approval denied: the turn still completes with a clear tool error.
      const denied = runClient([
        'run',
        '--task',
        'Use the bash tool to run: echo denied-probe. Pass sandbox_permissions=danger-full-access so an approval prompt appears. Do not explain.',
        '--cwd',
        WORK,
        '--conversation',
        'e2e-approval-deny',
        '--timeout',
        '120000',
      ])
      const denyResult = eventsOf(denied.frames, 'tool_result').at(-1)
      const denyFinal = eventsOf(denied.frames, 'final').at(-1)
      check('deny turn still completes', denied.code === 0 && Boolean(denyFinal), denied.stderr.trim().slice(-500))
      check('denied bash did not run', denyResult?.data?.ok === false, String(denyResult?.data?.text).slice(0, 200))
    }

    // 5. Replay after a reconnect (works without a model too).
    const replay = spawnSync(process.execPath, [CLIENT, 'resume', '--since', '0', '--dsh-home', DSH_HOME, '--json', '--quiet'], {
      encoding: 'utf8',
      timeout: 30_000,
    })
    const replayed = String(replay.stdout ?? '')
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line.startsWith('{'))
      .map((line) => JSON.parse(line))
    check('events.resume returns frames', replayed.length > 0, `code ${replay.status}`)
    const seqs = replayed.map((frame) => frame.seq).filter((seq) => typeof seq === 'number')
    check('replayed seq is strictly increasing', seqs.every((seq, index) => index === 0 || seq > seqs[index - 1]))

    const report = {
      generatedAt: new Date().toISOString(),
      channelPort,
      checks,
      passed: checks.filter((entry) => entry.ok).length,
      failed: checks.filter((entry) => !entry.ok).length,
    }
    fs.writeFileSync(path.join(WORKSPACE, 'e2e', 'last-report.json'), `${JSON.stringify(report, null, 2)}\n`)
    log(`${report.passed} passed, ${report.failed} failed`)
    return report.failed === 0 ? 0 : 1
  } finally {
    if (booted?.child) {
      booted.child.kill('SIGTERM')
      await new Promise((resolve) => setTimeout(resolve, 1500))
      if (booted.child.exitCode === null) booted.child.kill('SIGKILL')
    }
    if (!keep) fs.rmSync(ROOT, { recursive: true, force: true })
    else log(`kept ${ROOT}`)
  }
}

main()
  .then((code) => {
    process.exitCode = code
  })
  .catch((error) => {
    log(`FAILED ${error?.stack ?? error}`)
    process.exitCode = 1
  })
